//! Временная приостановка TUI для инструментов, которым нужен НАСТОЯЩИЙ
//! интерактивный терминал — пароль `sudo`, интерактивный `ssh`, вопрос
//! `ask_user`. Тот же приём, что уже применён для `/voice` в `repl.rs`,
//! но вынесен сюда как общий примитив, потому что нужен в нескольких
//! местах: `ask_user.rs`, `bash_tool.rs` (см. комментарии там).
//!
//! ## Почему это вообще было нужно
//! Пока работает TUI (`repl.rs`), терминал в raw-mode + alternate
//! screen — весь ввод разбирается через `crossterm::EventStream`
//! (посимвольно, без строчного редактирования/echo). Если в этот момент
//! где-то в дереве вызовов (инструмент `bash` запускает `sudo`, или
//! `ask_user` читает ответ) происходит ОБЫЧНОЕ блокирующее чтение stdin
//! (`std::io::stdin().read_line()`, или ещё хуже — `sudo` сам пытается
//! читать пароль с управляющего терминала без echo) — оно физически не
//! может получить нормальную строку: raw-mode отключает и построчную
//! буферизацию, и echo, на которые рассчитывает обычное чтение. С точки
//! зрения пользователя это выглядит как "терминал не отвечает, набор
//! бесполезен, приходится закрывать окно" — то, что было в жалобе.
//!
//! ## Что делает эта функция
//! Опускает raw-mode и alternate screen (терминал становится ОБЫЧНЫМ —
//! построчный ввод, echo, всё как всегда), выполняет переданное
//! блокирующее действие с реальным доступом к терминалу, затем поднимает
//! raw-mode и alternate screen обратно. TUI сам перерисуется на
//! следующем кадре (в `repl.rs` после каждого such вызова стоит
//! `terminal.clear()`).
//!
//! ЧЕСТНАЯ ОГОВОРКА: как и `/voice` (см. `repl.rs::run_voice_mode`),
//! использующий это код обычно блокирует поток исполнителя tokio на
//! время интерактивного ввода — это осознанный компромисс, а не
//! забытый `spawn_blocking`: сам смысл действия — "отдать пользователю
//! реальный терминал", и до его завершения TUI всё равно не может
//! ничего полезного показать.

use std::io;
use std::sync::atomic::{AtomicBool, Ordering};

/// Взводится `with_real_terminal()` после каждого возврата в TUI —
/// `repl.rs` проверяет этот флаг перед каждой перерисовкой и, если он
/// взведён, зовёт `Terminal::clear()`.
static NEEDS_REDRAW: AtomicBool = AtomicBool::new(false);

/// ИСПРАВЛЕНО (жалоба "bash нормально не выполняется, передача
/// управления не работает, опять в кашу" — после фикса NEEDS_REDRAW в
/// прошлом раунде): взведённого флага после возврата оказалось
/// НЕДОСТАТОЧНО. Реальная причина серьёзнее: пока `with_real_terminal`
/// держит терминал опущенным (raw-mode выключен, sudo/ask_user читают
/// реальный ввод), ГЛАВНЫЙ ЦИКЛ `repl.rs::run_app()` — это ОТДЕЛЬНАЯ
/// задача tokio, которая понятия не имеет, что терминал сейчас занят
/// кем-то другим. Он как ни в чём не бывало продолжает вызывать
/// `terminal.draw()` каждые ~120мс по своему тику, И ПРОДОЛЖАЕТ читать
/// `EventStream` (тот тоже читает stdin — напрямую конкурируя с
/// `read_line()`/сhtdin-чтением sudo за один и тот же поток байт).
/// Получались буквально ДВА процесса, дерущихся за один терминал
/// одновременно — отсюда каша ЕЩЁ ХУЖЕ, чем просто "кэш ratatui устарел".
///
/// Этот флаг — сигнал главному циклу "терминал занят, вообще не трогай
/// его" — `repl.rs` при `is_suspended() == true` не рисует TUI и не
/// опрашивает `EventStream` вообще, просто ждёт короткими интервалами.
static SUSPENDED: AtomicBool = AtomicBool::new(false);

/// Забрать и сбросить флаг "нужна полная перерисовка" — `repl.rs` зовёт
/// это перед каждым `terminal.draw()`.
pub fn take_needs_redraw() -> bool {
    NEEDS_REDRAW.swap(false, Ordering::SeqCst)
}

/// Терминал сейчас передан другому процессу (sudo/ssh/ask_user) —
/// главный цикл TUI должен полностью приостановиться, см. комментарий
/// у `SUSPENDED` выше.
pub fn is_suspended() -> bool {
    SUSPENDED.load(Ordering::SeqCst)
}

/// Выполнить `f` с настоящим (не raw-mode, не alternate screen)
/// терминалом, временно опустив TUI. Возвращает то, что вернула `f`.
/// Если поднять/опустить raw-mode не удалось — ошибка молча
/// игнорируется (`let _ =`) и `f` всё равно выполняется: лучше кривой
/// вывод, чем совсем не выполнить действие пользователя.
///
/// Печатает чёткую метку режима до и после (см. жалобу — "может пусть
/// будет в TUI, но с пометкой режима": полноценно остаться внутри
/// ratatui для НАСТОЯЩЕГО интерактивного терминала (пароль sudo, живая
/// ssh-сессия) нельзя — это требует полноценного PTY-виджета внутри
/// TUI, отдельная большая фича, не делал вслепую. Но хотя бы понятно
/// промаркировать переход — можно и нужно, это здесь и сделано).
pub fn with_real_terminal<F, T>(mode_label: &str, f: F) -> T
where
    F: FnOnce() -> T,
{
    use crossterm::execute;
    use crossterm::terminal::{disable_raw_mode, enable_raw_mode, Clear, ClearType, EnterAlternateScreen, LeaveAlternateScreen};

    SUSPENDED.store(true, Ordering::SeqCst);
    let _ = disable_raw_mode();
    let _ = execute!(io::stdout(), LeaveAlternateScreen, Clear(ClearType::All));
    println!("━━━ РЕЖИМ: {} — TUI приостановлен, управление у вас ━━━\n", mode_label);

    let result = f();

    println!("\n━━━ Возврат в TUI ━━━");
    let _ = enable_raw_mode();
    let _ = execute!(io::stdout(), Clear(ClearType::All), EnterAlternateScreen);
    NEEDS_REDRAW.store(true, Ordering::SeqCst);
    // Снимаем приостановку ПОСЛЕДНЕЙ — главный цикл не должен решить,
    // что можно рисовать/читать события, пока raw-mode ещё не поднят.
    SUSPENDED.store(false, Ordering::SeqCst);

    result
}

/// Похоже на `/sudo`, `/ssh` в начале команды (в т.ч. после `env`,
/// `time`, `&&`/`;`-цепочек) — используется `bash_tool.rs`, чтобы понять,
/// что команде скорее всего нужен настоящий терминал (пароль, ssh-сессия
/// с TTY), а не просто захват stdout/stderr.
pub fn looks_interactive(command: &str) -> bool {
    // Разбиваем по типичным разделителям команд, чтобы поймать
    // "cd /tmp && sudo apt update" не только "sudo apt update".
    command
        .split(|c| c == ';' || c == '&' || c == '|')
        .map(|part| part.trim())
        .any(|part| {
            let first_word = part.split_whitespace().next().unwrap_or("");
            matches!(first_word, "sudo" | "ssh" | "su" | "passwd" | "visudo")
                // sudo может стоять не первым словом, если команда начинается
                // с переменных окружения или `env`/`time`/`nice` перед ней.
                || part.split_whitespace().take(3).any(|w| w == "sudo" || w == "ssh")
        })
}
